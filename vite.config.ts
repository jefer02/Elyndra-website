import { defineConfig, type Plugin } from 'vite';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { resolve, relative } from 'node:path';
import { LOCALES, DEFAULT_LOCALE } from './src/i18n/index.ts';
import { documentShell, pagePath, INLINE_BOOT_JS, type PageCtx, type PageId } from './src/pages/layout.ts';
import { renderHome } from './src/pages/home.ts';
import { renderPrivacy, renderNotFound } from './src/pages/privacy.ts';
import type { ReleaseSnapshot } from './src/data.ts';

/**
 * Public origin of the deployed site, without a trailing slash (e.g. https://elyndra.example).
 * Set SITE_URL in the Cloudflare build variables. Without it, canonical/og:url are left out,
 * og:image is relative and the sitemap is not written (the build prints a warning).
 */
const SITE_URL = (process.env.SITE_URL ?? '').trim().replace(/\/+$/, '');

const ROOT = import.meta.dirname;

/** Every HTML entry: one per locale and page, plus the 404 page (English). */
const PAGES: { file: string; locale: (typeof LOCALES)[number]; page: PageId }[] = [
  ...LOCALES.flatMap((l) => [
    { file: `${l.prefix.slice(1) ? l.prefix.slice(1) + '/' : ''}index.html`, locale: l, page: 'home' as PageId },
    { file: `${l.prefix.slice(1) ? l.prefix.slice(1) + '/' : ''}privacy/index.html`, locale: l, page: 'privacy' as PageId },
  ]),
  { file: '404.html', locale: DEFAULT_LOCALE, page: '404' },
];

function readSnapshot(): ReleaseSnapshot {
  try {
    return JSON.parse(readFileSync(resolve(ROOT, 'public/data/releases.json'), 'utf8'));
  } catch {
    return { fetchedAt: null, releases: [] };
  }
}

function renderPage(file: string): string | null {
  const entry = PAGES.find((p) => p.file === file);
  if (!entry) return null;
  const ctx: PageCtx = { locale: entry.locale, page: entry.page, siteUrl: SITE_URL, snapshot: readSnapshot() };
  const t = entry.locale.dict;
  if (entry.page === 'home') return documentShell(ctx, t.meta.title, t.meta.description, renderHome(ctx));
  if (entry.page === 'privacy') return documentShell(ctx, t.meta.privacyTitle, t.meta.privacyDescription, renderPrivacy(ctx));
  return documentShell(ctx, t.meta.notFoundTitle, t.meta.description, renderNotFound(ctx));
}

const sha256 = (s: string) => createHash('sha256').update(s, 'utf8').digest('base64');

function headersFile(): string {
  const csp = [
    "default-src 'self'",
    `script-src 'self' 'sha256-${sha256(INLINE_BOOT_JS)}' 'wasm-unsafe-eval'`,
    "style-src 'self'",
    "img-src 'self' data: blob:",
    "font-src 'self'",
    "connect-src 'self' https://api.github.com",
    "manifest-src 'self'",
    "worker-src 'self' blob:",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'none'",
    "frame-ancestors 'none'",
    'upgrade-insecure-requests',
  ].join('; ');
  return `# Generated by vite.config.ts at build time. Edit there, not in dist/.
/*
  Content-Security-Policy: ${csp}
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=(), browsing-topics=()
  Cross-Origin-Opener-Policy: same-origin
  X-Frame-Options: DENY

/assets/*
  Cache-Control: public, max-age=31536000, immutable

/fonts/*
  Cache-Control: public, max-age=2592000

/img/*
  Cache-Control: public, max-age=604800, stale-while-revalidate=86400

/models/*
  Cache-Control: public, max-age=604800, stale-while-revalidate=86400

/data/*
  Cache-Control: public, max-age=300

/og.jpg
  Cache-Control: public, max-age=86400
`;
}

function elyndraPages(): Plugin {
  return {
    name: 'elyndra-pages',
    transformIndexHtml: {
      order: 'pre',
      handler(_html, ctx) {
        const file = relative(ROOT, ctx.filename).replace(/\\/g, '/');
        const out = renderPage(file);
        if (!out) throw new Error(`No renderer for ${file}`);
        return out;
      },
    },
    generateBundle() {
      this.emitFile({ type: 'asset', fileName: '_headers', source: headersFile() });
      const robots = ['User-agent: *', 'Allow: /', 'Disallow: /404.html'];
      if (SITE_URL) {
        robots.push('', `Sitemap: ${SITE_URL}/sitemap.xml`);
        const today = new Date().toISOString().slice(0, 10);
        const urls = PAGES.filter((p) => p.page !== '404')
          .map((p) => {
            const alts = LOCALES.map(
              (l) => `    <xhtml:link rel="alternate" hreflang="${l.code}" href="${SITE_URL}${pagePath(l, p.page)}"/>`,
            ).join('\n');
            return `  <url>\n    <loc>${SITE_URL}${pagePath(p.locale, p.page)}</loc>\n    <lastmod>${today}</lastmod>\n${alts}\n  </url>`;
          })
          .join('\n');
        this.emitFile({
          type: 'asset',
          fileName: 'sitemap.xml',
          source: `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n${urls}\n</urlset>\n`,
        });
      } else {
        this.warn('SITE_URL is not set: no sitemap.xml, no canonical/og:url, relative og:image. Set it for production builds.');
      }
      this.emitFile({ type: 'asset', fileName: 'robots.txt', source: robots.join('\n') + '\n' });
    },
    configureServer(server) {
      // Templates live in TypeScript imported by this config: reload the page when they change.
      server.watcher.add([resolve(ROOT, 'src/pages'), resolve(ROOT, 'src/i18n'), resolve(ROOT, 'public/data')]);
      server.watcher.on('change', (f) => {
        if (/[\\/]src[\\/](pages|i18n)[\\/]/.test(f)) server.restart();
      });
    },
  };
}

export default defineConfig({
  plugins: [elyndraPages()],
  build: {
    target: 'es2022',
    cssCodeSplit: true,
    assetsInlineLimit: 0,
    modulePreload: { polyfill: false },
    chunkSizeWarningLimit: 700,
    rollupOptions: {
      input: Object.fromEntries(PAGES.map((p) => [p.file.replace(/\.html$/, '').replace(/\//g, '-'), resolve(ROOT, p.file)])),
    },
  },
  server: { port: 5173 },
});
